def merge_i18n(lang: str, base: dict, extra: dict) -> dict:
    out = dict(base)
    out.update(extra)
    if lang in LANG_OVERRIDES:
        for k, v in LANG_OVERRIDES[lang].items():
            if k in out:
                out[k] = v
    return dict(sorted(out.items()))


